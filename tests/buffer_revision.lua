local revisions = require('buffer_revision')
local buf = vim.api.nvim_create_buf(false, true)
local original = { 'e: B', '', '=== ARTIKEL ===', '', 'Kop', '', 'Artikeltekst.' }
vim.api.nvim_buf_set_lines(buf, 0, -1, false, original)
local first = revisions.capture(buf)
vim.api.nvim_buf_set_lines(buf, 2, 2, false, { 'Melding: Facebook-tekst toegevoegd.' })
assert(revisions.matches(buf, first), 'een meldingsregel veroorzaakte een inhoudsconflict')
vim.api.nvim_buf_set_lines(buf, 2, 2, false, { '' })
assert(revisions.matches(buf, first), 'witruimte rond een meldingsblok veroorzaakte een inhoudsconflict')
local before = revisions.capture(buf)
vim.api.nvim_buf_set_lines(buf, 0, 0, false, { '---', 'editorial:', '  date_approval: {plan_sha256: test}', '---', '' })
local after = revisions.capture(buf)
assert(not revisions.matches(buf, first), 'workflowmetadata werd onvoorwaardelijk genegeerd')
assert(revisions.matches(buf, revisions.advance(first, { before = before, after = after })),
  'expliciete datumgoedkeuring bleef ten onrechte een conflict')
vim.api.nvim_buf_set_lines(buf, -1, -1, false, { 'Mijn echte toevoeging.' })
assert(not revisions.matches(buf, after), 'echte latere bewerking werd genegeerd')
local late_before = revisions.capture(buf)
assert(revisions.advance(first, { before = late_before, after = after }) == first,
  'systeemtransitie accepteerde een eerdere gebruikersbewerking')
vim.api.nvim_buf_set_lines(buf, 0, -1, false, original)
local body = revisions.capture(buf)
vim.api.nvim_buf_set_lines(buf, -1, -1, false, { 'Melding: Dit is artikelinhoud.' })
assert(not revisions.matches(buf, body), 'Melding: in de body werd ten onrechte genegeerd')
print('buffer revision: OK')
